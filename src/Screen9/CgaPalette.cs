namespace Screen9;

/// <summary>I 16 colori del testo CGA/EGA/VGA in RGB esatto (marrone 0xAA5500 compreso), nell'ordine di <see cref="ConsoleColor"/>
/// e degli attributi QBasic 0..15. Indipendenti dal tema del terminale.</summary>
public static class CgaPalette
{
    private static readonly PCRgb[] Colors =
    [
        new(0x00,0x00,0x00), new(0x00,0x00,0xAA), new(0x00,0xAA,0x00), new(0x00,0xAA,0xAA),
        new(0xAA,0x00,0x00), new(0xAA,0x00,0xAA), new(0xAA,0x55,0x00), new(0xAA,0xAA,0xAA),
        new(0x55,0x55,0x55), new(0x55,0x55,0xFF), new(0x55,0xFF,0x55), new(0x55,0xFF,0xFF),
        new(0xFF,0x55,0x55), new(0xFF,0x55,0xFF), new(0xFF,0xFF,0x55), new(0xFF,0xFF,0xFF)
    ];
    /// <summary>RGB del colore; i valori fuori da 0..15 usano i 4 bit bassi.</summary>
    public static PCRgb Rgb(ConsoleColor color) => Colors[(int)color & 15];
}
